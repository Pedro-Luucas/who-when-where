export type ShellKey = keyof (typeof SHELL_MESSAGES)["en"];

export function useShellT() {
  return translator(SHELL_MESSAGES, useLocale());
}

/** A shell string in the player's language, usable from Server Components. */
export function ShellText({ k, vars }: { k: ShellKey; vars?: Record<string, string | number> }) {
  return useShellT()(k, vars);
}
