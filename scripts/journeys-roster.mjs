// Famous journeys for Wayfarer.
//
// `title` is the English Wikipedia article used for the closing text and the
// "read more" link. Years are negative for BC. `mode` is how they travelled:
// sea | land | air | river | mixed.
//
// `stops` trace the route in order. Each is [lat, lon] for a plain waypoint
// (used only to bend the line around coasts) or [lat, lon, "Name", "Nome"]
// for a place that gets a dot and a label once the puzzle is over; the
// Portuguese name may be left out when it is the same. Keep the named stops
// to a handful per journey. Routes are schematic: good enough to recognise
// on a world map, not a navigation log.
const journey = (id, title, en, pt, start, end, mode, stops) => ({
  id,
  title,
  name: { en, pt },
  start,
  end,
  mode,
  stops,
});

