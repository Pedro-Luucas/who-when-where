export type SocialKey = keyof (typeof SOCIAL_MESSAGES)["en"];

type Vars = Record<string, string | number>;

function pick(locale: Locale) {
  const dictionary = SOCIAL_MESSAGES[locale] as Record<string, string>;
  const fill = translator(SOCIAL_MESSAGES, locale);
  return (key: SocialKey, vars?: Vars): string => {
    const singular = `${key}_one`;
    return fill((vars?.n === 1 && singular in dictionary ? singular : key) as SocialKey, vars);
  };
}

export function useSocialT() {
  const locale = useLocale();
  return { locale, t: pick(locale) };
}

/** A social string in the player's language, usable from Server Components. */
export function SocialText({ k }: { k: SocialKey }) {
  return useSocialT().t(k);
}

