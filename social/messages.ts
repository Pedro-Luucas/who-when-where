/** The message to show for a failed community action. */
export function socialError(error: unknown): SocialKey {
  if (!(error instanceof ApiError)) return "errGeneric";
  if (error.code === "invalid" && error.field === "body") return "errMessage";
  if (error.code === "invalid" && error.field === "username") return "errNoSuchPlayer";
  return BY_CODE[error.code] ?? "errGeneric";
}
