export type ConnectKey = keyof (typeof CONNECT_MESSAGES)["en"];

type Vars = Record<string, string | number>;

function pick(locale: Locale) {
  const dictionary = CONNECT_MESSAGES[locale] as Record<string, string>;
  const fill = translator(CONNECT_MESSAGES, locale);
  return (key: ConnectKey, vars?: Vars): string => {
    const singular = `${key}_one`;
    return fill((vars?.n === 1 && singular in dictionary ? singular : key) as ConnectKey, vars);
  };
}

export function useConnectT() {
  const locale = useLocale();
  return { locale, t: pick(locale) };
}

/** The tier's name: 0 Bronze … 4 Diamond. */
export const tierKey = (tier: number): ConnectKey => `tier_${Math.max(0, Math.min(4, tier))}` as ConnectKey;

/** Whether a failure means the API does not have this feature yet (or is down). */
export const isMissingFeature = (error: unknown): boolean =>
  error instanceof ApiError && (error.code === "not_found" || error.code === "unavailable" || error.status >= 500);

/** "5 min ago", "2 h ago". */
export function agoKey(at: number, now: number): { key: ConnectKey; n: number } {
  const minutes = Math.floor((now - at) / 60_000);
  if (minutes < 1) return { key: "justNow", n: 0 };
  if (minutes < 60) return { key: "minutesAgo", n: minutes };
  if (minutes < 60 * 24) return { key: "hoursAgo", n: Math.floor(minutes / 60) };
  return { key: "daysAgo", n: Math.floor(minutes / 1440) };
}
