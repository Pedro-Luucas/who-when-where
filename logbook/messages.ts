export type LogbookKey = keyof (typeof LOGBOOK_MESSAGES)["en"];

export function useLogbookT() {
  const locale = useLocale();
  return { locale, t: translator(LOGBOOK_MESSAGES, locale) };
}

/** A logbook string in the player's language, usable from Server Components. */
export function LogbookText({ k }: { k: LogbookKey }) {
  return useLogbookT().t(k);
}
